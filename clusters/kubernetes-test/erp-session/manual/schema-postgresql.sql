-- Isolated from ERP business tables; run once using the existing application role.
CREATE SCHEMA IF NOT EXISTS webui_session;

CREATE TABLE IF NOT EXISTS webui_session.spring_session (
    PRIMARY_ID CHAR(36) NOT NULL PRIMARY KEY,
    SESSION_ID CHAR(36) NOT NULL,
    CREATION_TIME BIGINT NOT NULL,
    LAST_ACCESS_TIME BIGINT NOT NULL,
    MAX_INACTIVE_INTERVAL INT NOT NULL,
    EXPIRY_TIME BIGINT NOT NULL,
    PRINCIPAL_NAME VARCHAR(100)
);
CREATE UNIQUE INDEX IF NOT EXISTS spring_session_ix1 ON webui_session.spring_session (SESSION_ID);
CREATE INDEX IF NOT EXISTS spring_session_ix2 ON webui_session.spring_session (EXPIRY_TIME);
CREATE INDEX IF NOT EXISTS spring_session_ix3 ON webui_session.spring_session (PRINCIPAL_NAME);

CREATE TABLE IF NOT EXISTS webui_session.spring_session_attributes (
    SESSION_PRIMARY_ID CHAR(36) NOT NULL,
    ATTRIBUTE_NAME VARCHAR(200) NOT NULL,
    ATTRIBUTE_BYTES BYTEA NOT NULL,
    PRIMARY KEY (SESSION_PRIMARY_ID, ATTRIBUTE_NAME),
    FOREIGN KEY (SESSION_PRIMARY_ID) REFERENCES webui_session.spring_session(PRIMARY_ID) ON DELETE CASCADE
);
